#!/usr/bin/env python3
"""Write ``src/plainread/_build.py`` with the build number, commit and date.

CI runs this before building packages, so every wheel, binary and container
knows exactly which build it is:

    python scripts/stamp_build.py --build-number 42 --commit "$GITHUB_SHA"

Without arguments it uses GitHub Actions' environment (``GITHUB_RUN_NUMBER``,
``GITHUB_SHA``) or falls back to "local" and ``git rev-parse HEAD``.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import subprocess
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "plainread" / "_build.py"


def git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-number", default=os.environ.get("GITHUB_RUN_NUMBER", "local"))
    parser.add_argument("--commit", default=os.environ.get("GITHUB_SHA") or git_commit())
    parser.add_argument(
        "--date", default=dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    )
    args = parser.parse_args()
    TARGET.write_text(
        '"""Generated by scripts/stamp_build.py. Do not edit."""\n\n'
        f"BUILD_NUMBER = {str(args.build_number)!r}\n"
        f"COMMIT = {str(args.commit)!r}\n"
        f"BUILD_DATE = {str(args.date)!r}\n",
        encoding="utf-8",
    )
    print(f"Stamped build {args.build_number} ({args.commit[:12]}) at {args.date} -> {TARGET}")


if __name__ == "__main__":
    main()
